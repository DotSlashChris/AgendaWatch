"""Oct 19 2026: Provo had 21 hits out of 26 notices, nearly all noise. Real lines from the cached
Provo / West Jordan / Cottonwood Heights packets. Noise must not match; real rental lines must."""
import agenda_watch as aw
from conftest import CH

KW = {"keywords": ["short-term rental", "STR", "rental license", "business license", "zoning",
                   "conditional use", "transient tax", "occupancy"]}


def hits(text, doc="Council Meeting - Meeting Packet.pdf"):
    return aw.find_hits(text, aw.build_keyword_matchers(KW), doc_name=doc)


def terms(text, **kw):
    return sorted({h["matched"] for h in hits(text, **kw)})


