#!/usr/bin/env python3
"""Generate cloudflare/src/catalog.gen.ts from config.json (run by wrangler's build step on every deploy).
The edge needs the catalog city slugs to route /cities/<slug> and to build sitemap.xml without waking
the container. Never edit catalog.gen.ts by hand."""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import aw_cities  # noqa: E402

OUT = ROOT / "cloudflare" / "src" / "catalog.gen.ts"


def render():
    slugs = [p["slug"] for p in aw_cities.city_pages(aw_cities.load_config(ROOT / "config.json"))]
    return ("// GENERATED by tools/gen_worker_catalog.py from config.json. Do not edit.\n"
            f"export const CITY_SLUGS: readonly string[] = {json.dumps(slugs)};\n")


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(ROOT)}")
